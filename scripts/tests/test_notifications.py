def event(index, **fields):
    row = record(model="model-a", request_id=f"request-{index}", **fields)
    row.update(resource="topic-a", service="gateway", environment="prod", upstream_provider="provider-a")
    return row


def claim(directory, rows=(), size=100):
    document = {"kind": "scan", "complete": True,
                **enqueue_and_claim(directory, list(rows), ["example"], batch_size=size)}
    existing = {event_id for group in document["associations"] for event_id in group["event_ids"]}
    document["associations"].extend({"event_ids": [row["event_id"]], "trace_status": "complete",
                                     "completeness": "observed_boundaries", "outcome": "failed"}
                                    for row in document["alerts"] if row["event_id"] not in existing)
    return document


def classification(row, **changes):
    return {"certainty": "confirmed", "classification": {
        "category": "content_policy", "reason": "input_content_rejected", "subject": "input",
        "summary": "输入内容未通过审核", "evidence_event_ids": [row["event_id"]],
        "evidence_quote": row["error_message"], **changes}}


class ClassificationTests(unittest.TestCase):
    def test_different_wording_requires_agent_evidence(self):
        rows = [event(1, error_message="Input content violates policy"),
                event(2, error_message="Content rejected by safety policy")]
        document = {"records": rows}
        self.assertEqual(len(notification_groups(document)), 2)
        analyses = {row["event_id"]: classification(row) for row in rows}
        groups = notification_groups(document, analyses)
        self.assertEqual(len(groups), 1)
        self.assertEqual(len(groups[0]["records"]), 2)
        self.assertIn("输入内容未通过审核", render(document, analyses))
        # Descriptions generated by the model never define group identity.
        analyses[rows[0]["event_id"]].update(judgment="One explanation", recommendation="Try A")
        analyses[rows[1]["event_id"]].update(judgment="Another explanation", recommendation="Try B")
        self.assertEqual(len(notification_groups(document, analyses)), 1)

    def test_bad_evidence_and_broad_unknown_category_fall_back(self):
        rows = [event(1, error_message="Content rejected"), event(2, error_message="Policy violation")]
        for changes in ({"category": "upstream_error"}, {"category": []}, {"evidence_event_ids": ["foreign"]},
                        {"evidence_quote": "not in the logs"}, {"subject": ""}, {"reason": "arbitrary sentence"}):
            analyses = {row["event_id"]: classification(row, **changes) for row in rows}
            groups = notification_groups({"records": rows}, analyses)
            self.assertEqual(len(groups), 2)
            self.assertTrue(all(group["classification_issues"] for group in groups))

    def test_codes_subjects_upstreams_keys_and_models_keep_boundaries(self):
        for field, changed in (("error_code", "OTHER"), ("upstream_provider", "other"),
                               ("authorization", "Bearer different-secret-987654"), ("model", "other-model"),
                               ("environment", "test"), ("operation", "DeleteAsset"), ("path", "/other")):
            rows = [event(1), event(2)]
            rows[1][field] = changed
            analyses = {row["event_id"]: classification(row) for row in rows}
            self.assertEqual(len(notification_groups({"records": rows}, analyses)), 2, field)
        rows = [event(1), event(2)]
        analyses = {row["event_id"]: classification(row) for row in rows}
        analyses[rows[1]["event_id"]]["classification"]["subject"] = "output"
        self.assertEqual(len(notification_groups({"records": rows}, analyses)), 2)

    def test_unconfirmed_and_conflicting_classifications_are_not_used(self):
        row = event(1)
        analysis = classification(row)
        analysis["certainty"] = "suspected"
        self.assertFalse(notification_groups({"records": [row]}, {row["event_id"]: analysis})[0]["classifications"])
        analysis["certainty"] = "confirmed"
        group = notification_groups({"records": [row], "association": {"error_conflict": True}}, {row["event_id"]: analysis})[0]
        self.assertFalse(group["mergeable"])

    def test_analysis_shape_and_duplicate_ids_are_rejected(self):
        row = event(1)
        for analyses in ([], {row["event_id"]: "text"}):
            with self.assertRaises(LogError):
                notification_groups({"records": [row]}, analyses)
        with self.assertRaises(LogError):
            notification_groups({"records": [row, row]})

    def test_request_counts_do_not_count_log_lines_as_requests(self):
        rows = [event(1), event(1, marker="second-log"), event(2)]
        text = render({"records": rows})
        self.assertIn("3 条异常日志 · 2 个已识别请求", text)
        self.assertNotIn("失败请求", text)
        rows[2]["request_id"] = ""
        self.assertIn("1 条缺少请求标识", render({"records": rows}))

    def test_masks_are_not_used_as_key_identity(self):
        rows = [event(1, authorization="abcd-first-secret-wxyz"), event(2, authorization="abcd-second-secret-wxyz")]
        with tempfile.TemporaryDirectory() as directory:
            document = claim(directory, rows)
            self.assertEqual(document["alerts"][0]["authorization"], document["alerts"][1]["authorization"])
            fingerprints = load_authorization_fingerprints(directory, [row["event_id"] for row in rows])
            self.assertEqual(len(notification_groups(document, fingerprints=fingerprints)), 2)
            self.assertEqual(len(notification_groups(document)), 2)

    def test_report_id_alone_cannot_enable_truncation(self):
        row = event(1, error_message="x" * 1000)
        self.assertIn("x" * 1000, render({"records": [row], "notification_report_id": "a" * 20}))


class NotificationStateTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.directory = self.temp.name
        self.config = {"notifications": {"test": {"provider": "feishu"}}}
        self.clock = self.enterContext(patch("time.time", return_value=1000))
        self.enterContext(patch("cloud_log_delivery.time.sleep"))
        environment = {name: os.environ[name] for name in ("TEMP", "TMP", "SystemRoot") if name in os.environ}
        environment["FEISHU_WEBHOOK"] = "https://open.feishu.cn/open-apis/bot/v2/hook/synthetic"
        self.enterContext(patch.dict(os.environ, environment, clear=True))
        self.post = self.enterContext(patch("cloud_log_delivery.post"))
        self.addCleanup(self.temp.cleanup)

    def send(self, document, analyses=None):
        return send_document(self.config, "test", document, analyses or {}, self.directory)

    def test_first_immediate_repeat_deferred_then_delivered_without_new_logs(self):
        self.assertEqual(self.send(claim(self.directory, [event(1)]))["acknowledged_events"], 1)
        self.clock.return_value = 1100
        second = claim(self.directory, [event(2)])
        result = self.send(second)
        self.assertEqual((result["sent_messages"], result["acknowledged_events"], result["deferred_events"]), (0, 0, 1))
        self.assertEqual(result["next_notification_at"], 1900)
        waiting = claim(self.directory)
        self.assertEqual((waiting["alerts"], waiting["available_count"], waiting["deferred_count"]), ([], 0, 1))
        self.clock.return_value = 1901
        due = claim(self.directory)
        self.assertEqual(due["alerts"], second["alerts"])
        self.assertEqual(self.send(due)["acknowledged_events"], 1)
        self.assertEqual(self.post.call_count, 2)

    def test_deferred_semantic_analysis_is_saved_and_redacted(self):
        first, second = event(1, error_message="Content rejected"), event(2, error_message="Policy violation")
        self.send(claim(self.directory, [first]), {first["event_id"]: classification(first)})
        self.clock.return_value = 1100
        analysis = classification(second)
        analysis["judgment"] = "Credential " + TOKEN
        result = self.send(claim(self.directory, [second]), {second["event_id"]: analysis})
        self.assertEqual(result["deferred_events"], 1)
        for file in Path(self.directory).rglob("*"):
            if file.is_file():
                self.assertNotIn(TOKEN.encode(), file.read_bytes())
        self.clock.return_value = 1901
        due = claim(self.directory)
        self.assertIn(second["event_id"], due["notification_analyses"])
        self.assertEqual(self.send(due)["acknowledged_events"], 1)

    def test_new_problem_and_critical_level_bypass_cooldown(self):
        self.send(claim(self.directory, [event(1)]))
        self.clock.return_value = 1100
        for row in (event(2, error_message="Different error"), event(3, level="CRITICAL")):
            self.assertEqual(self.send(claim(self.directory, [row]))["sent_messages"], 1)

    def test_severity_increase_and_query_failure_bypass_cooldown(self):
        self.send(claim(self.directory, [event(1, level="WARNING")]))
        self.clock.return_value = 1100
        self.assertEqual(self.send(claim(self.directory, [event(2)]))["sent_messages"], 1)
        bad = claim(self.directory, [event(3)])
        bad["complete"] = False
        self.assertEqual(self.send(bad)["sent_messages"], 1)

    def test_repeat_threshold_advances_waiting_records(self):
        self.config["notifications"]["test"]["repeat_escalation_count"] = 2
        self.send(claim(self.directory, [event(1)]))
        self.clock.return_value = 1100
        self.assertEqual(self.send(claim(self.directory, [event(2)]))["deferred_events"], 1)
        self.assertEqual(self.send(claim(self.directory, [event(3)]))["acknowledged_events"], 1)
        waiting = claim(self.directory)
        self.assertEqual(len(waiting["alerts"]), 1)
        self.assertEqual(self.send(waiting)["acknowledged_events"], 1)

    def test_cooldown_can_be_disabled(self):
        self.config["notifications"]["test"]["repeat_interval_seconds"] = 0
        self.send(claim(self.directory, [event(1)]))
        self.clock.return_value = 1100
        self.assertEqual(self.send(claim(self.directory, [event(2)]))["acknowledged_events"], 1)

    def test_two_targets_have_independent_cooldowns_and_receipts(self):
        os.environ["FEISHU_WEBHOOK"] = json.dumps([
            "https://open.feishu.cn/open-apis/bot/v2/hook/first", "https://open.feishu.cn/open-apis/bot/v2/hook/second"])
        self.send(claim(self.directory, [event(1)]))
        db = sqlite3.connect(Path(self.directory) / "outbox.sqlite3")
        try:
            with db:
                one = db.execute("SELECT destination FROM notification_history ORDER BY destination LIMIT 1").fetchone()[0]
                db.execute("UPDATE notification_history SET last_sent=0 WHERE destination=?", (one,))
        finally:
            db.close()
        self.clock.return_value = 1100
        result = self.send(claim(self.directory, [event(2)]))
        self.assertEqual((result["sent_messages"], result["deferred_events"]), (1, 1))
        self.clock.return_value = 1901
        result = self.send(claim(self.directory))
        self.assertEqual((result["sent_messages"], result["acknowledged_events"]), (1, 1))

    def test_partial_card_failure_resumes_frozen_plan_even_with_smaller_batch(self):
        rows = [event(i, error_message=f"Distinct error {i}") for i in range(20)]
        document = claim(self.directory, rows)
        self.post.side_effect = [None, LogError("simulated network failure")]
        with self.assertRaises(LogError):
            self.send(document)
        successful = deepcopy(self.post.call_args_list[0].args[2])
        failed = deepcopy(self.post.call_args_list[1].args[2])
        self.post.reset_mock(side_effect=True)
        retry = claim(self.directory, size=1)
        self.assertEqual(len(retry["alerts"]), 20)
        self.assertEqual(self.send(retry, {rows[0]["event_id"]: {"judgment": "New words"}})["acknowledged_events"], 20)
        self.assertEqual(self.post.call_args_list[0].args[2], failed)
        self.assertNotIn(successful, [call.args[2] for call in self.post.call_args_list])

    def test_report_retains_full_error_and_masks_before_truncation(self):
        row = event(1, error_message="a" * 230 + TOKEN + "z" * 500)
        result = self.send(claim(self.directory, [row]))
        payload = json.dumps(self.post.call_args.args[2], ensure_ascii=False)
        self.assertNotIn(TOKEN, payload)
        self.assertIn("完整内容见详情", payload)
        report = read_report(self.directory, result["report_id"])
        text = report["document"]["alerts"][0]["error_message"]
        self.assertIn("z" * 500, text)
        self.assertNotIn(TOKEN, text)
        self.assertNotIn("raw", report["document"]["alerts"][0])
        with self.assertRaises(LogError):
            read_report(self.directory, "../../private")

    def test_invalid_notification_settings_fail(self):
        for item in (-1, True, "900", 1000001):
            with self.assertRaises(LogError):
                settings({"repeat_interval_seconds": item})

    def test_mixed_new_and_delayed_groups_ack_only_delivered_events(self):
        self.send(claim(self.directory, [event(1)]))
        self.clock.return_value = 1100
        repeated, new = event(2), event(3, error_message="Another problem")
        result = self.send(claim(self.directory, [repeated, new]))
        self.assertEqual((result["acknowledged_events"], result["deferred_events"]), (1, 1))
        db = sqlite3.connect(Path(self.directory) / "outbox.sqlite3")
        try:
            self.assertIsNone(db.execute("SELECT sent FROM events WHERE event_id=?", (repeated["event_id"],)).fetchone()[0])
            self.assertIsNotNone(db.execute("SELECT sent FROM events WHERE event_id=?", (new["event_id"],)).fetchone()[0])
        finally:
            db.close()

    def test_failure_does_not_start_cooldown(self):
        self.post.side_effect = LogError("unknown network result")
        with self.assertRaises(LogError):
            self.send(claim(self.directory, [event(1)]))
        db = sqlite3.connect(Path(self.directory) / "outbox.sqlite3")
        try:
            self.assertEqual(db.execute("SELECT COUNT(*) FROM notification_history").fetchone()[0], 0)
            self.assertEqual(db.execute("SELECT COUNT(*) FROM target_receipts").fetchone()[0], 0)
        finally:
            db.close()
        self.post.side_effect = None
        self.clock.return_value = 1100
        self.assertEqual(self.send(claim(self.directory))["acknowledged_events"], 1)

    def test_overlapping_target_plans_are_claimed_as_one_component(self):
        from cloud_log_notify_state import create_plan
        rows = [event(i) for i in range(3)]
        document = claim(self.directory, rows)
        receipt(self.directory, document["delivery_id"], False)
        for target, members in (("one", rows[:2]), ("two", rows[1:])):
            create_plan(self.directory, target, [{"id": target, "records": members, "level": 4}], [{"message": "synthetic"}])
        replay = claim(self.directory, size=1)
        self.assertEqual({row["event_id"] for row in replay["alerts"]}, {row["event_id"] for row in rows})
        self.assertEqual(replay["available_count"], 0)

    def test_saved_analysis_is_cleared_after_new_enrichment(self):
        from cloud_log_enrichment import enrich
        row = event(1)
        document = claim(self.directory, [row])
        document["notification_analyses"] = {row["event_id"]: classification(row)}
        updated = enrich(document, [])
        self.assertNotIn("notification_analyses", updated)

    def test_legacy_outbox_migrates_without_losing_payload(self):
        from cloud_log_state import open_store
        with tempfile.TemporaryDirectory() as directory:
            db = sqlite3.connect(Path(directory) / "outbox.sqlite3")
            try:
                db.execute("CREATE TABLE events(event_id TEXT PRIMARY KEY,connection_id TEXT,payload TEXT,"
                           "created REAL,sent REAL,delivery_id TEXT,lease_until REAL,sending INTEGER DEFAULT 0)")
                db.execute("INSERT INTO events(event_id,connection_id,payload,created) VALUES('legacy','example','{}',1)")
                db.commit()
            finally:
                db.close()
            db = open_store(directory)
            try:
                self.assertEqual(db.execute("SELECT payload,notify_after FROM events WHERE event_id='legacy'").fetchone(), ('{}', 0))
                self.assertIn("notification_payload", {row[1] for row in db.execute("PRAGMA table_info(events)")})
            finally:
                db.close()


